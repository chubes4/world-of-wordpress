<h2 class="wp-block-heading">Librarian Shelf Ledger</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>The Librarian office keeps the Pattern Library from becoming an old map of a younger world. A shelf is healthy when every reusable pattern has a role, a route, and enough air around its live preview.</p>
<!-- /wp:paragraph -->

<!-- wp:columns -->
<div class="wp-block-columns"><!-- wp:column -->
<div class="wp-block-column"><!-- wp:heading {"level":3} -->
<h3 class="wp-block-heading">Shelf audit</h3>
<!-- /wp:heading -->

<!-- wp:list {"ordered":true} -->
<ol><!-- wp:list-item -->
<li><strong>Count the living pieces.</strong> Compare the pattern directory with the public catalog before adding another pattern.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>Name the role.</strong> Every pattern should belong to orientation, world-sense, civic instrument, route/feed, ritual/festival, or stranger-signal work.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>Render the proof.</strong> Important patterns should appear somewhere public, either in the Pattern Library previews or in the civic room where they work.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>Prune stale claims.</strong> Counts, category labels, and next-use guidance must change when the shelf changes.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>Protect breathing room.</strong> A preview card should clarify the pattern without explaining it twice.</li>
<!-- /wp:list-item --></ol>
<!-- /wp:list --></div>
<!-- /wp:column -->

<!-- wp:column -->
<div class="wp-block-column"><!-- wp:heading {"level":3} -->
<h3 class="wp-block-heading">Current repair</h3>
<!-- /wp:heading -->

<!-- wp:list -->
<ul><!-- wp:list-item -->
<li><strong>Observed defect:</strong> the catalog still spoke as if only ten reusable surfaces existed, even after the civic rooms produced many working instruments.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>Repair:</strong> give the Librarian a ledger, expand the catalog roles, and make the Pattern Library acknowledge the newer civic instruments without overcrowding the old preview shelf.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>Next useful pass:</strong> add selective live previews for the highest-value civic instruments after the shelf shows which ones visitors need to compare directly.</li>
<!-- /wp:list-item --></ul>
<!-- /wp:list --></div>
