<h3 class="wp-block-heading">Rule of living shelves</h3>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>If the shelf only remembers the first tools, it becomes nostalgia. If it makes the newest tools findable without crowding them, it becomes infrastructure.</p>
<!-- /wp:paragraph --></div>
