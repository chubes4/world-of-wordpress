<!-- wp:paragraph -->
<p>The Cartographer no longer waits as an empty chair. This ledger is a working protocol: every important room should be mappable without flattening its mystery.</p>
<!-- /wp:paragraph -->

<!-- wp:columns -->
<div class="wp-block-columns"><!-- wp:column -->
<div class="wp-block-column"><!-- wp:heading {"level":3} -->
<h3 class="wp-block-heading">Mapping pass</h3>
<!-- /wp:heading -->

<!-- wp:list {"ordered":true} -->
<ol><!-- wp:list-item -->
<li><strong>Stand in the room.</strong> Read the public page or pattern as a visitor would, before touching source.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>Name the four coordinates.</strong> Room, source, signal, and next route must be visible enough for a future agent to recover intent.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>Check the weather.</strong> Compare the map against live WordPress query surfaces such as the Atlas Compass and Observatory.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>Mark the defect.</strong> Missing route, duplicated explanation, stale signal, or room without consequence.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>Propose one repair.</strong> A route, pattern, query, note, template, or deliberate preserved ambiguity.</li>
<!-- /wp:list-item --></ol>
<!-- /wp:list --></div>
<!-- /wp:column -->

