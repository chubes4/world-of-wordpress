<div class="wp-block-group has-background" style="border-color:#7c3aed;border-width:1px;background-color:#faf5ff;margin-top:1rem;margin-bottom:1rem;padding-top:1rem;padding-right:1rem;padding-bottom:1rem;padding-left:1rem"><!-- wp:heading {"level":3} -->
<h3 class="wp-block-heading">Librarian audit</h3>
<!-- /wp:heading -->

<!-- wp:paragraph {"fontSize":"small"} -->
<p class="has-small-font-size">The Librarian office now has a ledger for shelf audits. Use it when the library falls behind the world: count the living pieces, name each role, render public proof, prune stale claims, and protect breathing room around live previews.</p>
<!-- /wp:paragraph --></div>
<!-- /wp:group -->

<!-- wp:group {"metadata":{"name":"Preview card ritual"},"style":{"border":{"width":"1px"},"spacing":{"padding":{"top":"1rem","right":"1rem","bottom":"1rem","left":"1rem"},"margin":{"top":"1rem","bottom":"1rem"}},"color":{"background":"#f0fdf4"}},"layout":{"type":"constrained"}} -->
<div class="wp-block-group has-background" style="border-width:1px;background-color:#f0fdf4;margin-top:1rem;margin-bottom:1rem;padding-top:1rem;padding-right:1rem;padding-bottom:1rem;padding-left:1rem"><!-- wp:heading {"level":3} -->
<h3 class="wp-block-heading">Preview card ritual</h3>
<!-- /wp:heading -->

<!-- wp:paragraph {"fontSize":"small"} -->
<p class="has-small-font-size">On the dedicated Pattern Library page, keep each preview card as a display case: name the pattern, describe why it exists, then render the live pattern inside the card. Do not fold the display-case wrapper back into the reusable pattern unless the pattern itself truly needs that frame everywhere it appears.</p>
<!-- /wp:paragraph --></div>
<!-- /wp:group -->

<!-- wp:group {"metadata":{"name":"Card polish sequence"},"style":{"border":{"width":"1px"},"spacing":{"padding":{"top":"1rem","right":"1rem","bottom":"1rem","left":"1rem"},"margin":{"top":"1rem","bottom":"1rem"}},"color":{"background":"#fefce8"}},"layout":{"type":"constrained"}} -->
<div class="wp-block-group has-background" style="border-width:1px;background-color:#fefce8;margin-top:1rem;margin-bottom:1rem;padding-top:1rem;padding-right:1rem;padding-bottom:1rem;padding-left:1rem"><!-- wp:heading {"level":3} -->
<h3 class="wp-block-heading">Card polish sequence</h3>
<!-- /wp:heading -->

<!-- wp:paragraph {"fontSize":"small"} -->
<p class="has-small-font-size">Polish preview cards in this order: first make the label plain, then make the purpose useful, then let the live pattern breathe. If a card needs a second explanatory paragraph, test whether the pattern itself is unclear before adding more frame around it.</p>
<!-- /wp:paragraph --></div>
<!-- /wp:group -->

<!-- wp:group {"metadata":{"name":"Card review questions"},"style":{"border":{"width":"1px"},"spacing":{"padding":{"top":"1rem","right":"1rem","bottom":"1rem","left":"1rem"},"margin":{"top":"1rem","bottom":"1rem"}},"color":{"background":"#ecfeff"}},"layout":{"type":"constrained"}} -->
<div class="wp-block-group has-background" style="border-width:1px;background-color:#ecfeff;margin-top:1rem;margin-bottom:1rem;padding-top:1rem;padding-right:1rem;padding-bottom:1rem;padding-left:1rem"><!-- wp:heading {"level":3} -->
<h3 class="wp-block-heading">Card review questions</h3>
<!-- /wp:heading -->

<!-- wp:paragraph {"fontSize":"small"} -->
<p class="has-small-font-size">When a preview card feels noisy, ask three questions before adding more frame: can a visitor tell what pattern is being shown, can they tell why it belongs in the library, and can the live pattern still breathe without the catalog explaining it twice?</p>
<!-- /wp:paragraph --></div>
<!-- /wp:group -->

<!-- wp:group {"metadata":{"name":"Room split threshold"},"style":{"border":{"width":"1px"},"spacing":{"padding":{"top":"1rem","right":"1rem","bottom":"1rem","left":"1rem"},"margin":{"top":"1rem","bottom":"1rem"}},"color":{"background":"#fff7ed"}},"layout":{"type":"constrained"}} -->
<div class="wp-block-group has-background" style="border-width:1px;background-color:#fff7ed;margin-top:1rem;margin-bottom:1rem;padding-top:1rem;padding-right:1rem;padding-bottom:1rem;padding-left:1rem"><!-- wp:heading {"level":3} -->
<h3 class="wp-block-heading">Room split threshold</h3>
<!-- /wp:heading -->

<!-- wp:paragraph {"fontSize":"small"} -->
<p class="has-small-font-size">Do not split the Pattern Library merely because the shelf is long. Split only when a visitor would learn more from a dedicated room than from the live catalog: when one role needs its own introduction, when examples need comparison space, or when a new route would reduce confusion instead of creating another door to maintain.</p>
<!-- /wp:paragraph --></div>
