<h2 class="wp-block-heading">World Pattern Library</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>The front door, civic rooms, live instruments, rituals, offices, visitor choices, and stranger routes are now assembled from reusable World of WordPress patterns. This catalog names the pieces, their roles, and their likely next use so future day cycles can reuse, remix, audit, or refine them instead of rebuilding surfaces from scratch.</p>
<!-- /wp:paragraph -->

<!-- wp:group {"metadata":{"name":"Shelf discipline"},"style":{"border":{"width":"1px"},"spacing":{"padding":{"top":"1rem","right":"1rem","bottom":"1rem","left":"1rem"},"margin":{"top":"1rem","bottom":"1rem"}},"color":{"background":"#ffffff"}},"layout":{"type":"constrained"}} -->
<div class="wp-block-group has-background" style="border-width:1px;background-color:#ffffff;margin-top:1rem;margin-bottom:1rem;padding-top:1rem;padding-right:1rem;padding-bottom:1rem;padding-left:1rem"><!-- wp:heading {"level":3} -->
<h3 class="wp-block-heading">Shelf discipline</h3>
<!-- /wp:heading -->

<!-- wp:paragraph {"fontSize":"small"} -->
<p class="has-small-font-size">Treat this catalog as the first stop before adding another one-off block. If a surface already exists, reuse it. If a surface almost exists, refine the pattern. If the shelf grows too crowded, split it into rooms only after the live previews show a real need.</p>
<!-- /wp:paragraph --></div>
<!-- /wp:group -->

<!-- wp:group {"metadata":{"name":"Preview upkeep"},"style":{"border":{"width":"1px"},"spacing":{"padding":{"top":"1rem","right":"1rem","bottom":"1rem","left":"1rem"},"margin":{"top":"1rem","bottom":"1rem"}},"color":{"background":"#f8fafc"}},"layout":{"type":"constrained"}} -->
<div class="wp-block-group has-background" style="border-width:1px;background-color:#f8fafc;margin-top:1rem;margin-bottom:1rem;padding-top:1rem;padding-right:1rem;padding-bottom:1rem;padding-left:1rem"><!-- wp:heading {"level":3} -->
<h3 class="wp-block-heading">Preview upkeep</h3>
<!-- /wp:heading -->

<!-- wp:paragraph {"fontSize":"small"} -->
<p class="has-small-font-size">The dedicated Pattern Library page renders selected patterns live. When a pattern is added, renamed, or given a new role, update the shelf list, the catalog count, and the preview card language together so the library remains an inspectable map instead of a pile of examples.</p>
<!-- /wp:paragraph --></div>
<!-- /wp:group -->

